assert len(ANSWERS) == 200, f"ожидалось 200 ответов, получено {len(ANSWERS)}"
assert len(set(ANSWERS)) == len(ANSWERS), "в списке ответов есть повторы"

# сколько последних ответов не повторять одному человеку
NO_REPEAT_WINDOW = 40


def pick_answer(seen: list) -> tuple:
    """Возвращает (текст ответа, обновлённый список недавних индексов)."""
    recent = set(seen[-NO_REPEAT_WINDOW:])
    choices = [i for i in range(len(ANSWERS)) if i not in recent]
    idx = random.choice(choices)
    return ANSWERS[idx], (seen + [idx])[-NO_REPEAT_WINDOW:]
