def full_parts(points: dict) -> list:
    """Возвращает список сообщений полного разбора."""
    a, b, v, g, d, e, z = (points[k] for k in ("A", "B", "V", "G", "D", "E", "Z"))

    def line(title, letter, num):
        return f"{title} ({letter}): {num} — {NAMES[num]}"

    scheme = (
        "🧭 Ваши точки матрицы\n\n"
        + "\n".join([
            line("Характер", "А", a),
            line("Таланты", "Б", b),
            line("Главная задача", "В", v),
            line("Кармический хвост", "Г", g),
            line("Внутренний центр", "Д", d),
            line("Деньги", "З", z),
            line("Любовь", "Е", e),
        ])
    )
    return [
        scheme,
        f"🎭 Характер: {a} {NAMES[a]}\n\n{ARCANA[a]['core']}",
        f"💎 Таланты: {b} {NAMES[b]}\n\n{ARCANA[b]['talent']}",
        f"💰 Деньги: {z} {NAMES[z]}\n\n{ARCANA[z]['money']}",
        f"❤️ Любовь: {e} {NAMES[e]}\n\n{ARCANA[e]['love']}",
        f"🎯 Главная задача: {v} {NAMES[v]}\n\n{ARCANA[v]['lesson']}",
        f"🪢 Кармический хвост: {g} {NAMES[g]}\n\n{ARCANA[g]['shadow']}",
        DISCLAIMER,
    ]
