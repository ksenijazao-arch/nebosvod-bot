"""Матрица судьбы: расчёт точек по дате рождения и тексты по 22 арканам.

Используется классическая схема: точки А (день), Б (месяц), В (год), Г (их сумма),
Д (центр) и производные Е (А+Б) и З (В+Г). Числа сворачиваются до 22.
"""


def reduce22(n: int) -> int:
    while n > 22:
        n = sum(int(c) for c in str(n))
    return n


def compute(day: int, month: int, year: int) -> dict:
    a = reduce22(day)
    b = reduce22(month)
    v = reduce22(sum(int(c) for c in str(year)))
    g = reduce22(a + b + v)
    d = reduce22(a + b + v + g)
    e = reduce22(a + b)
    z = reduce22(v + g)
    return {"A": a, "B": b, "V": v, "G": g, "D": d, "E": e, "Z": z}


