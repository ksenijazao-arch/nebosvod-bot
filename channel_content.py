def _sky_events():
    import json, os
    with open(os.path.join(os.path.dirname(__file__), "sky_events.json"), encoding="utf-8") as f:
        return [(date.fromisoformat(d), t, kind) for d, t, kind, _ in json.load(f)]


SKY = _sky_events()


def week_overview(monday):
    """События недели: точные даты из sky_events.json (Swiss Ephemeris, сидерический
    зодиак, день по Москве) плюс священные дни и Наваратри."""
    import sacred, navaratri
    days = [monday + timedelta(days=d) for d in range(7)]
    lunar_feast = {d for d in list(sacred.DAYS) + [navaratri.MAHALAYA]
                   if d == navaratri.MAHALAYA or any(k in sacred.DAYS.get(d, "") for k in ("Пурнима", "Амавасья", "Дивали"))}
    ev = []
    for day in days:
        for d, t, kind in SKY:
            if d != day:
                continue
            if kind == "moon" and any(abs((day - f).days) <= 1 for f in lunar_feast):
                continue
            if kind == "ingress" and t.startswith("Солнце") and day in sacred.DAYS and "Санкранти" in sacred.DAYS[day]:
                continue
            ev.append((day, t))
        if day in sacred.DAYS:
            title = sacred.DAYS[day].split("</b>")[0].split("<b>")[1].strip().rstrip(".")
            title = title.replace("Сегодня ", "")
            if not title.startswith(("Пурнима", "Амавасья")):
                ev.append((day, title))
        if day == navaratri.MAHALAYA:
            ev.append((day, "Махалая, новолуние и день поминовения предков"))
        if day in navaratri.DATE_TO_NIGHT:
            n = navaratri.DATE_TO_NIGHT[day]
            again = len(navaratri.NIGHT_DATES[n]) > 1 and navaratri.NIGHT_DATES[n][-1] == day
            ev.append((day, f"Наваратри, {'продолжается ' if again else ''}{n + 1}-я ночь: {navaratri.GODDESSES[n][0]}"))
            if n == 8:
                ev.append((day, "Виджаядашами, день победы"))
    end = monday + timedelta(days=6)
    M = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"]
    span = (f"{monday.day}–{end.day} {M[end.month - 1]}" if monday.month == end.month
            else f"{monday.day} {M[monday.month - 1]} – {end.day} {M[end.month - 1]}")
    lines = [f"🗓 <b>Неделя в небе: {span}</b>", ""]
    if ev:
        for day, t in ev:
            t = t[0].upper() + t[1:]
            lines.append(f"• {WD[day.weekday()]} {day.day} — {t.rstrip('.')}")
    else:
        lines.append("Тихая неделя: крупных событий в небе нет, хорошее время доделывать начатое.")
    lines += ["", "Даты по ведическому (сидерическому) зодиаку. Как неделя ляжет на вашу карту, покажет "
              f"бесплатный недельный прогноз в боте: <a href=\"{BOT}\">Небосвод</a>. Он приходит по понедельникам всем, кто прошёл разбор."]
    return "\n".join(lines)


def midday_item(day):
    """('text', html) или ('poll', (вопрос, варианты))."""
    wd = day.weekday()
    if wd == 0:
        return "text", week_overview(day)
    if wd in (1, 3, 6):
        return "poll", poll_for(day)
    if wd in (2, 4):
        return "text", fact_for(day)
    return "text", practice_for(day)
