def _moon_sign_at(jd):
    return ac.sign_of(ac.sidereal_lon(ac.moon_longitude(jd), jd))["sign"]


def _find_moon_ingress(jd_start, jd_end):
    """Момент смены знака Луны внутри интервала (jd) или None."""
    s0 = _moon_sign_at(jd_start)
    step = 1 / 48
    t = jd_start
    while t < jd_end:
        t2 = t + step
        if _moon_sign_at(t2) != s0:
            lo, hi = t, t2
            for _ in range(20):
                mid = (lo + hi) / 2
                if _moon_sign_at(mid) == s0:
                    lo = mid
                else:
                    hi = mid
            return hi, _moon_sign_at(hi)
        t = t2
    return None


def _jd_to_msk_hm(jd):
    dt = datetime(2000, 1, 1, 12, tzinfo=timezone.utc) + timedelta(days=jd - 2451545.0)
    return dt.astimezone(MSK).strftime("%H:%M")


def _aspect_texts(jd):
    keys = list(PLANET_RU)
    lons = {k: (ac.sun_longitude(jd) if k == "sun" else ac.planet_longitude(k, jd)) for k in keys}
    found = []
    for i, a in enumerate(keys):
        for b in keys[i + 1:]:
            d = ac.ang_diff(lons[a], lons[b])
            for angle, kind in ((0, "conj"), (60, "sext"), (90, "sq"), (120, "tri"), (180, "opp")):
                orb = abs(d - angle)
                if orb <= 1.5:
                    found.append((orb, a, b, kind))
    found.sort()
    out = []
    for orb, a, b, kind in found[:2]:
        A, B, ta, tb = PLANET_RU[a], PLANET_RU[b], PLANET_THEME[a], PLANET_THEME[b]
        if kind == "conj":
            out.append(f"{A} ({ta}) соединяется с {PLANET_INS[b]} ({tb}): эти темы сегодня сливаются в одну.")
        elif kind in ("sext", "tri"):
            out.append(f"{A} ({ta}) и {B} ({tb}) в гармонии: хороший момент соединить эти сферы.")
        else:
            out.append(f"{A} ({ta}) и {B} ({tb}) в напряжении: не торопитесь с выводами и резкими ответами.")
    return out


def build_daily_post(day: date, bot_link: str) -> str:
    # полдень по Москве — опорная точка дня
    jd_noon = ac.to_jd(day.year, day.month, day.day, 9, 0)
    jd_day_start = ac.to_jd(day.year, day.month, day.day, 0, 0) - 3 / 24  # 00:00 мск
    jd_day_end = jd_day_start + 1

    moon_start_sign = _moon_sign_at(jd_day_start + 7 / 24)  # к 7 утра мск
    ingress = _find_moon_ingress(jd_day_start + 7 / 24, jd_day_end)

    elong = ac.norm360(ac.moon_longitude(jd_noon) - ac.sun_longitude(jd_noon))
    phase_name, phase_text = next((n, t) for lo, hi, n, t in PHASES if lo <= elong < hi)

    nak = ac.nakshatra_of(ac.sidereal_lon(ac.moon_longitude(jd_noon), jd_noon))
    nak_idx = ac.NAKSHATRAS.index(nak["name"])

    stations, stationing = [], set()
    for k in ("mercury", "venus", "mars", "jupiter", "saturn"):
        r_before = ac.is_retrograde(k, jd_day_start)
        r_after = ac.is_retrograde(k, jd_day_end)
        if r_before != r_after:
            stationing.add(k)
            stations.append(f"{PLANET_RU[k]} ({PLANET_THEME[k]}) {'разворачивается назад' if r_after else 'разворачивается вперёд'}: эти темы сегодня звучат особенно громко.")
    retro = [k for k in ("mercury", "venus", "mars", "jupiter", "saturn") if ac.is_retrograde(k, jd_noon) and k not in stationing]

    sign_for_day = moon_start_sign
    good, bad = MOON_DAY[sign_for_day]

    lines = [f"🌙 <b>Небо на {day.day} {MONTHS_GEN[day.month - 1]}, {WEEKDAYS[day.weekday()]}</b>", ""]
    moon_line = f"Луна {ac.v_predlog(moon_start_sign)} {ac.SIGN_PREPOSITIONAL[moon_start_sign]}, накшатра {nak['name']}. Фаза: {phase_name}."
    if ingress:
        moon_line += f" Около {_jd_to_msk_hm(ingress[0])} мск Луна перейдёт в {SIGN_ACC[ingress[1]]}."
    lines += [moon_line, "", phase_text, ""]
    for block in (navaratri.channel_block(day), sacred.channel_block(day)):
        if block:
            lines += [block, ""]
    lines += [f"✅ <b>На что направить силы:</b> {good}.", f"⛔ <b>Лучше избегать:</b> {bad}.", ""]

    events = stations + _aspect_texts(jd_noon)
    if events:
        lines.append("✨ <b>Главное в небе:</b>\n" + "\n".join("• " + e for e in events))
        lines.append("")
    if retro:
        names = ", ".join(PLANET_RU[k] for k in retro)
        lines.append(f"🔁 Ретроградны: {names}. Хорошее время пересматривать и доделывать, хуже — начинать с нуля.")
        lines.append("")
    lines.append(f"🕉 <b>Накшатра дня {nak['name']}:</b> {NAK_KEY[nak_idx]}.")
    lines.append("")
    lines.append(f"💫 Это общий фон дня. Как он ляжет именно на вашу карту, покажет личный прогноз в боте: <a href=\"{bot_link}\">Небосвод</a>")
    return "\n".join(lines)
