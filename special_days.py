def due(today_iso):
    """События, которые нужно отправить сегодня (по Москве)."""
    return [d for d in SPECIAL_DAYS if d["send_on"] == today_iso]


def upcoming(today_iso, limit=5):
    return [d for d in SPECIAL_DAYS if d["send_on"] >= today_iso][:limit]
