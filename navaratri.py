def channel_block(day):
    """Блок для ежедневного поста в канале или None."""
    if PITRI_START <= day < MAHALAYA:
        left = (MAHALAYA - day).days
        return ("🕯 <b>Питри Пакша, дни предков.</b> До Махалаи "
                f"{left} {'день' if left == 1 else ('дня' if left < 5 else 'дней')}. Хорошо вспоминать предков по именам, "
                "кормить птиц, ставить воду и огонь, повернувшись к югу. Крупные покупки и громкие старты лучше перенести.")
    if day == MAHALAYA:
        return ("🕯 <b>Сегодня Махалая</b>, новолуние, последний день Питри Пакши. В этот день поминают всех предков, "
                "даже тех, чьих имён уже не знают. Зажгите свечу и поблагодарите свой род. Завтра начинается Наваратри.")
    if day in DATE_TO_NIGHT:
        n = DATE_TO_NIGHT[day]
        name, planet, essence, color, practice, mantra = GODDESSES[n]
        second = NIGHT_DATES[n][-1] == day and len(NIGHT_DATES[n]) > 1
        head = f"🪔 <b>Наваратри, {'продолжается ' if second else ''}{n + 1}-я ночь: {name}.</b>"
        text = (f"{head} {essence[0].upper() + essence[1:]}. Цвет дня: {color}. {practice} "
                f"Мантра: «{mantra}».")
        if n == 8:
            text += ("\n\n🏹 <b>И сегодня же Виджаядашами</b>, день победы: с 13:15 по Индии (10:45 мск) наступает Дашами. "
                     "Один из самых благоприятных дней года, чтобы начать важное дело.")
        text += "\n\nУзнать свою Богиню Наваратри по дате рождения можно бесплатно в боте."
        return text
    return None
