def fmt_dates(ds):
    if len(ds) == 1:
        return f"{ds[0].day} {MONTHS_GEN[ds[0].month - 1]}"
    return f"{ds[0].day} и {ds[1].day} {MONTHS_GEN[ds[1].month - 1]}"


def goddess_for_nakshatra(nak_index):
    planet = DASHA_ORDER[nak_index % 9]
    idx = next(i for i, g in enumerate(GODDESSES) if g[1] == planet)
    return idx, planet


def feature_active(today):
    return today <= FEATURE_UNTIL


