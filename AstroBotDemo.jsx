/* ============ АСТРОНОМИЯ: Солнце, Луна, Асцендент (проверено отдельным расчётом) ============ */
function norm360(x) { x = x % 360; if (x < 0) x += 360; return x; }

function toJD(y, m, d, utcHour, utcMinute) {
  let yy = y, mm = m;
  const frac = (utcHour + utcMinute / 60) / 24;
  if (mm <= 2) { yy -= 1; mm += 12; }
  const A = Math.floor(yy / 100);
  const B = 2 - A + Math.floor(A / 4);
  const JD0 = Math.floor(365.25 * (yy + 4716)) + Math.floor(30.6001 * (mm + 1)) + d + B - 1524.5;
  return JD0 + frac;
}

function sunLongitude(JD) {
  const d = JD - 2451545.0;
  const L = norm360(280.460 + 0.9856474 * d);
  const g = (norm360(357.528 + 0.9856003 * d) * Math.PI) / 180;
  const lambda = L + 1.915 * Math.sin(g) + 0.02 * Math.sin(2 * g);
  return norm360(lambda);
}

function moonLongitude(JD) {
  const d = JD - 2451545.0;
  const Lm = norm360(218.316 + 13.176396 * d);
  const Mm = (norm360(134.963 + 13.064993 * d) * Math.PI) / 180;
  const D = (norm360(297.85 + 12.190749 * d) * Math.PI) / 180;
  let lambda = Lm + 6.289 * Math.sin(Mm);
  lambda += -1.274 * Math.sin(Mm - 2 * D);
  lambda += 0.658 * Math.sin(2 * D);
  return norm360(lambda);
}

function obliquity(JD) {
  const T = (JD - 2451545.0) / 36525;
  return 23.439291 - 0.0130042 * T;
}

function gst(JD) {
  const T = (JD - 2451545.0) / 36525;
  const g = 280.46061837 + 360.98564736629 * (JD - 2451545.0) + 0.000387933 * T * T - (T * T * T) / 38710000;
  return norm360(g);
}

function ascendant(JD, latDeg, lonDeg) {
  const lst = norm360(gst(JD) + lonDeg);
  const lstRad = (lst * Math.PI) / 180;
  const eps = (obliquity(JD) * Math.PI) / 180;
  const lat = (latDeg * Math.PI) / 180;
  const y = Math.cos(lstRad);
  const x = -(Math.sin(eps) * Math.tan(lat) + Math.cos(eps) * Math.sin(lstRad));
  return norm360((Math.atan2(y, x) * 180) / Math.PI);
}

