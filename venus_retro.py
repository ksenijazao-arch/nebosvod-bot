    def xy(lon, r):
        # асцендент/первый дом слева, как в классической карте
        a = math.radians(180 + (lon - first_idx * 30))
        return cx + r * math.cos(a), cy - r * math.sin(a)

    d.ellipse([cx - R, cy - R, cx + R, cy + R], outline=GOLD, width=2)
