def _jd_label(jd):
    y, m, d = ac.jd_to_ymd(jd)[:3]
    return f"{int(d)} {MONTHS_GEN[int(m) - 1]}"


def _venus(jd):
    return ac.planet_longitude("venus", jd)


def _house_from(sign_name, first_sign_name):
    return (ac.SIGNS.index(sign_name) - ac.SIGNS.index(first_sign_name)) % 12 + 1


def find_hits(chart):
    """Точные касания транзитной Венеры (соединение, квадрат, оппозиция)
    к натальным планетам в период тени. Возвращает список
    (planet, angle, [jd, ...]) только для планет, которых Венера касается."""
    hits = []
    for key in ("sun", "moon", "mercury", "venus", "mars", "jupiter", "saturn"):
        natal = ac.point_lon(chart[key]) + 0.5
        for angle in (0, 90, 180):
            targets = [ac.norm360(natal + angle)] if angle in (0, 180) else [ac.norm360(natal + 90), ac.norm360(natal - 90)]
            for target in targets:
                dates = []
                jd = SEARCH_FROM
                prev = ac.norm360(_venus(jd) - target + 180) - 180
                while jd < SEARCH_TO:
                    jd2 = jd + 1
                    cur = ac.norm360(_venus(jd2) - target + 180) - 180
                    if (prev <= 0 < cur or cur <= 0 < prev) and abs(prev - cur) < 5 and jd2 <= SEARCH_TO:
                        dates.append(jd2)
                    prev, jd = cur, jd2
                if dates:
                    hits.append((key, angle, dates))
    return hits


def compute(chart):
    has_time = bool(chart.get("rising"))
    first = chart["rising"]["sign"] if has_time else chart["sun"]["sign"]
    h_scorpio = _house_from("Скорпион", first)
    h_libra = _house_from("Весы", first)

    moon_sid = ac.sidereal_lon(ac.point_lon(chart["moon"]) + 0.5, chart["birth_jd"])
    moon_sid_sign = ac.sign_of(moon_sid)["sign"]
    j_libra = _house_from("Весы", moon_sid_sign)
    j_virgo = _house_from("Дева", moon_sid_sign)

    now_jd = ac.to_jd(2026, 10, 1, 12, 0)
    timeline = ac.dasha_timeline(chart["birth_jd"], moon_sid, years_ahead=130)
    cur = ac.current_dasha(timeline, now_jd)
    dasha_planet = cur[0] if cur else None

    return {
        "has_time": has_time, "first_sign": first,
        "h_scorpio": h_scorpio, "h_libra": h_libra,
        "moon_sid_sign": moon_sid_sign, "j_libra": j_libra, "j_virgo": j_virgo,
        "hits": find_hits(chart), "dasha": dasha_planet,
        "natal_venus_sign": chart["venus"]["sign"],
    }


def _dates_text(dates, today_jd):
    parts = []
    for j in dates:
        parts.append(_jd_label(j) + (" — уже было" if j < today_jd else ""))
    return ", ".join(parts)


