def _f(size, bold=False):
    return ImageFont.truetype(os.path.join(_FONTS, "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"), size)


def _center(draw, cx, y, text, font, fill):
    b = draw.textbbox((0, 0), text, font=font)
    draw.text((cx - (b[2] - b[0]) / 2, y - b[1]), text, font=font, fill=fill)


def render_card(chart, data, out_path, sign_glyphs, today_jd=None):
    today_jd = today_jd or ac.to_jd(2026, 10, 1, 0, 0)
    W, H = 1080, 1350
